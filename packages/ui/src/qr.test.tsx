describe('encodeQr', () => {
  it('matches an independent encoder module by module (v3 and v9 with version info)', () => {
    for (const ref of REFERENCE) {
      const m = encodeQr(ref.text, { mask: ref.mask });
      expect(m?.map((row) => row.map((c) => (c ? '1' : '0')).join(''))).toEqual(ref.rows);
    }
  });

  it('picks the smallest version and rejects payloads over version 10', () => {
    expect(encodeQr('WIFI:T:nopass;S:Host;;')?.length).toBe(25);
    expect(encodeQr('x'.repeat(300))).toBeNull();
  });

  it('draws one square per dark module inside a quiet zone', () => {
    expect(qrPath([[true, false]], 4)).toBe('M4 4h1v1h-1z');
  });
});

describe('QrCode', () => {
  it('renders an accessible SVG, or nothing for oversized payloads', () => {
    const { container, rerender } = render(
      <QrCode value="WIFI:T:nopass;S:Host;;" label="QR kód" />,
    );
    const svg = container.querySelector('svg');
    expect(svg?.getAttribute('aria-label')).toBe('QR kód');
    expect(svg?.getAttribute('viewBox')).toBe('0 0 33 33');
    rerender(<QrCode value={'x'.repeat(300)} label="QR" />);
    expect(container.querySelector('svg')).toBeNull();
  });
});
