"""Raster base layers of the INVENTED demo floor plans (dev server, e2e, screenshots).

Rasterises the demo vector plans (``modules/robots/src/map/demo.ts``, read from the
built ``dist`` – run ``pnpm --filter @homebrain/module-robots build`` first) into a
Roborock-like pixel grid (50 map units per pixel, room / wall / floor type bytes) and
renders it with the production renderer (``robots/raster_map.py``), so dev shows exactly
what the integration serves. Never feed real house maps into this script.

    node --version  # >= 23 (type stripping)
    python scripts/build_robot_demo_rasters.py
"""

from __future__ import annotations

import json
import math
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.homebrain.robots.raster_map import (  # noqa: E402
    LAYER_BASE,
    LAYER_WALLS,
    THEMES,
    raster_bounds,
    raster_layers,
    render_png,
)
from custom_components.homebrain.robots.vector_map import (  # noqa: E402
    MAP_INSIDE,
    MAP_WALL,
    PIXEL_UNITS,
    ImageBlock,
)

ASSETS = ROOT / "apps/panel/src/dev-assets/robots"
BOUNDS_TS = ROOT / "modules/robots/src/map/demoRaster.ts"
WALL_HALF_PX = 0.8  # demo walls are ~8–10 cm thick, like the real wall layer


def demo_maps() -> dict[int, dict]:
    script = (
        "const m = await import('./modules/robots/dist/map/demo.js');"
        "const out = {};"
        "for (const s of [1, 2, 3]) { const r = m.demoVectorMap(s, 0);"
        " if (r.available) out[s] = r.map; }"
        "console.log(JSON.stringify(out));"
    )
    raw = subprocess.run(
        ["node", "--input-type=module", "-e", script],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return {int(k): v for k, v in json.loads(raw).items()}


def _inside(ring: list[tuple[float, float]], x: float, y: float) -> bool:
    hit = False
    for (ax, ay), (bx, by) in zip(ring, ring[1:] + ring[:1], strict=True):
        if (ay > y) != (by > y) and x < ax + (y - ay) * (bx - ax) / (by - ay):
            hit = not hit
    return hit


def _seg_dist(px: float, py: float, a: tuple[float, float], b: tuple[float, float]) -> float:
    dx, dy = b[0] - a[0], b[1] - a[1]
    t = 0.0 if not (dx or dy) else ((px - a[0]) * dx + (py - a[1]) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    return math.hypot(px - a[0] - t * dx, py - a[1] - t * dy)


def rasterise(vector: dict) -> ImageBlock:
    x0, y0, x1, y1 = vector["bounds"]
    left, top = math.floor(x0 / PIXEL_UNITS), math.floor(y0 / PIXEL_UNITS)
    width, height = math.ceil(x1 / PIXEL_UNITS) - left, math.ceil(y1 / PIXEL_UNITS) - top

    def px(flat: list[int]) -> list[tuple[float, float]]:
        return [
            (flat[i] / PIXEL_UNITS - left, flat[i + 1] / PIXEL_UNITS - top)
            for i in range(0, len(flat) - 1, 2)
        ]

    rooms = [(room["id"], [px(p) for p in room["polygons"]]) for room in vector["rooms"]]
    floor = [px(p) for p in vector["floor"]]
    walls = [px(w) for w in vector["walls"]]
    data = bytearray(width * height)
    for y in range(height):
        for x in range(width):
            cx, cy = x + 0.5, y + 0.5
            value = 0
            if any(_inside(ring, cx, cy) for ring in floor):
                value = MAP_INSIDE
            for room_id, rings in rooms:
                if _inside(rings[0], cx, cy) and not any(_inside(h, cx, cy) for h in rings[1:]):
                    value = (room_id << 3) | 7
                    break
            if any(
                _seg_dist(cx, cy, a, b) <= WALL_HALF_PX
                for line in walls
                for a, b in zip(line, line[1:], strict=False)
            ):
                value = MAP_WALL
            data[y * width + x] = value
    return ImageBlock(top, left, width, height, bytes(data))


def main() -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    bounds: dict[int, list[int]] = {}
    for slot, vector in demo_maps().items():
        layers = raster_layers(rasterise(vector))
        bounds[slot] = raster_bounds(layers)
        for theme in THEMES:
            for layer, suffix in ((LAYER_BASE, ""), (LAYER_WALLS, "-walls")):
                png = render_png(layers, theme, layer=layer)
                (ASSETS / f"demo-{slot}-{theme}{suffix}.png").write_bytes(png)
                print(f"demo-{slot}-{theme}{suffix}.png {len(png) // 1024} KB")
    lines = [
        "// Generated by scripts/build_robot_demo_rasters.py – do not edit.",
        "/** Placement (map units) of the invented demo raster base layers per robot slot. */",
        "export const DEMO_RASTER_BOUNDS: Record<number, [number, number, number, number]> = {",
        *(f"  {slot}: [{', '.join(str(v) for v in b)}]," for slot, b in sorted(bounds.items())),
        "};",
        "",
    ]
    BOUNDS_TS.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
