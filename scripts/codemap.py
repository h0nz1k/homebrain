#!/usr/bin/env python3
"""Deterministic code map for agents: files, docstrings, signatures and internal imports.

Reads only tracked files (``git ls-files``) and the code itself — no LLM, no network, no
timestamps, so two runs over the same tree print byte-identical output. Python is parsed
with ``ast``; TS/TSX/JS go through ``scripts/codemap-ts.mjs`` (TypeScript compiler API,
one batch call). It does not type-check, follow third-party imports or invent missing docs.
See docs/codemap.md.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import posixpath
import re
import shutil
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

DEFAULT_SCOPE = ("custom_components/", "modules/", "packages/", "apps/", "scripts/")
PY_EXT = (".py",)
TS_EXT = (".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs")
SKIP_DIRS = {"node_modules", "dist", "dist-catalog", "build", "coverage", "__pycache__"}
TEST_RE = re.compile(r"(^|/)(tests?|__tests__)/|\.(test|spec)\.[^/]+$")
GENERATED_NAME_RE = re.compile(r"\.(gen|generated)\.[^/]+$")
GENERATED_HEAD_RE = re.compile(
    r"^\s*(?://|#|/\*+|\*)\s*(?:@generated\b|auto-?generated\b|generated\s+by\b)", re.I | re.M
)
TS_RESOLVE_EXT = (".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs")
MAX_SIG = 140
MAX_DOC = 120
NOTE_RESERVE = 160
HELPER = Path(__file__).resolve().with_name("codemap-ts.mjs")


@dataclass
class Symbol:
    """One documented unit of a file: class, function, const, type, … (methods in ``members``)."""

    kind: str
    name: str
    sig: str
    doc: str
    members: list[Symbol] = field(default_factory=list)


@dataclass
class FileMap:
    """Outline of one source file; ``deps`` are repo-relative paths of internal imports."""

    path: str
    doc: str = ""
    symbols: list[Symbol] = field(default_factory=list)
    deps: list[str] = field(default_factory=list)


class CodemapError(Exception):
    """User-facing failure (bad argument, missing tool); printed without a traceback."""


def _clip(text: str, limit: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _first_line(doc: str | None) -> str:
    for line in (doc or "").splitlines():
        if line.strip():
            return _clip(line.strip(), MAX_DOC)
    return ""


# --- file selection ------------------------------------------------------------------------


def tracked_files(root: Path) -> list[str]:
    """All files tracked by git under ``root`` (sorted, repo-relative, POSIX separators)."""
    try:
        out = subprocess.run(
            ["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True
        ).stdout
    except (OSError, subprocess.CalledProcessError) as err:
        raise CodemapError(f"git ls-files selhalo v {root}: {err}") from err
    return sorted(p for p in out.decode().split("\0") if p)


def is_generated(root: Path, path: str) -> bool:
    """Generated sources (``*.gen.ts``, header "Generated by …") are data, not code to map."""
    if GENERATED_NAME_RE.search(path):
        return True
    try:
        with open(root / path, encoding="utf-8", errors="replace") as fh:
            head = "".join(fh.readline() for _ in range(3))
    except OSError:
        return True
    return bool(GENERATED_HEAD_RE.search(head))


def select_files(
    root: Path, tracked: list[str], paths: list[str] | None, include_tests: bool
) -> list[str]:
    """Source files in scope: PATH filter (or the default scope), minus tests/builds/generated."""
    prefixes = tuple(paths) if paths else DEFAULT_SCOPE + (("tests/",) if include_tests else ())
    out = []
    for p in tracked:
        if not p.endswith(PY_EXT + TS_EXT) or p.endswith(".d.ts"):
            continue
        if not any(p == pre or p.startswith(pre.rstrip("/") + "/") for pre in prefixes):
            continue
        if SKIP_DIRS.intersection(p.split("/")[:-1]):
            continue
        if not include_tests and TEST_RE.search(p):
            continue
        if not (root / p).is_file() or is_generated(root, p):
            continue
        out.append(p)
    return out


# --- Python ---------------------------------------------------------------------------------


def _py_sig(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    sig = f"{fn.name}({ast.unparse(fn.args)})"
    if fn.returns is not None:
        sig += f" -> {ast.unparse(fn.returns)}"
    if isinstance(fn, ast.AsyncFunctionDef):
        sig = "async " + sig
    if any(isinstance(d, ast.Name) and d.id == "property" for d in fn.decorator_list):
        sig = "@property " + sig
    return _clip(sig, MAX_SIG)


def _py_module_file(parts: list[str], tracked: set[str]) -> str | None:
    base = "/".join(parts)
    for cand in (f"{base}.py", f"{base}/__init__.py"):
        if cand in tracked:
            return cand
    return None


def _py_imports(path: str, tree: ast.Module, tracked: set[str]) -> set[str]:
    pkg = path.split("/")[:-1]
    deps: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if hit := _py_module_file(alias.name.split("."), tracked):
                    deps.add(hit)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                up = node.level - 1
                if up > len(pkg):
                    continue
                parts = pkg[: len(pkg) - up] if up else list(pkg)
            else:
                parts = []
            if node.module:
                parts = parts + node.module.split(".")
            if not parts:
                continue
            module = _py_module_file(parts, tracked)
            for alias in node.names:
                # `from pkg import submodule` depends on the submodule file itself.
                sub = _py_module_file(parts + [alias.name], tracked)
                if sub:
                    deps.add(sub)
                elif module:
                    deps.add(module)
    deps.discard(path)
    return deps


def outline_python(root: Path, path: str, tracked: set[str]) -> FileMap:
    """Module docstring, public top-level classes (+ public methods) and functions, imports."""
    source = (root / path).read_text(encoding="utf-8", errors="replace")
    try:
        tree = ast.parse(source, filename=path)
    except SyntaxError as err:
        return FileMap(path, doc=f"(syntax error: line {err.lineno})")
    fm = FileMap(path, doc=_first_line(ast.get_docstring(tree)))
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            cls = Symbol(
                "class",
                node.name,
                _clip(f"class {node.name}" + (f"({bases})" if bases else ""), MAX_SIG),
                _first_line(ast.get_docstring(node)),
            )
            for item in node.body:
                if isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef) and not (
                    item.name.startswith("_")
                ):
                    cls.members.append(
                        Symbol(
                            "method", item.name, _py_sig(item), _first_line(ast.get_docstring(item))
                        )
                    )
            fm.symbols.append(cls)
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and not (
            node.name.startswith("_")
        ):
            fm.symbols.append(
                Symbol("function", node.name, _py_sig(node), _first_line(ast.get_docstring(node)))
            )
    fm.deps = sorted(_py_imports(path, tree, tracked))
    return fm


# --- TypeScript / JavaScript ----------------------------------------------------------------


def workspace_packages(root: Path, tracked: list[str]) -> dict[str, str]:
    """Workspace package name (from ``package.json``) -> its repo-relative directory."""
    out: dict[str, str] = {}
    for p in tracked:
        if p.endswith("/package.json") and not SKIP_DIRS.intersection(p.split("/")):
            try:
                name = json.loads((root / p).read_text(encoding="utf-8")).get("name")
            except (OSError, ValueError):
                continue
            if isinstance(name, str) and name:
                out[name] = p.rsplit("/", 1)[0]
    return out


def _ts_resolve_file(base: str, tracked: set[str]) -> str | None:
    stem, ext = posixpath.splitext(base)
    cands = [base]
    if ext in (".js", ".jsx", ".mjs", ".cjs"):
        cands += [stem + e for e in (".ts", ".tsx", ".mts", ".cts")]
    cands += [base + e for e in TS_RESOLVE_EXT]
    cands += [f"{base}/index{e}" for e in TS_RESOLVE_EXT]
    return next((c for c in cands if c in tracked), None)


def resolve_ts_import(
    path: str, spec: str, tracked: set[str], packages: dict[str, str]
) -> str | None:
    """Relative or workspace (``@homebrain/x[/sub]``) specifier -> repo path; else ``None``."""
    spec = spec.split("?", 1)[0]
    if spec.startswith("."):
        base = posixpath.normpath(posixpath.join(posixpath.dirname(path), spec))
        return None if base.startswith("..") else _ts_resolve_file(base, tracked)
    parts = spec.split("/")
    name_len = 2 if spec.startswith("@") else 1
    pkg_dir = packages.get("/".join(parts[:name_len]))
    if pkg_dir is None:
        return None
    sub = "/".join(parts[name_len:])
    if not sub:
        return pkg_dir
    return _ts_resolve_file(f"{pkg_dir}/{sub}", tracked) or f"{pkg_dir}/{sub}"


def _symbol_from_json(d: dict) -> Symbol:
    return Symbol(
        d["kind"],
        d["name"],
        d["sig"],
        d.get("doc", ""),
        [Symbol("method", m["name"], m["sig"], m.get("doc", "")) for m in d.get("members", [])],
    )


def outline_ts(root: Path, files: list[str], tracked: list[str]) -> dict[str, FileMap]:
    """One batch call of codemap-ts.mjs for all TS/JS files, imports resolved here."""
    if not files:
        return {}
    node = shutil.which("node")
    if node is None:
        raise CodemapError("TS/JS soubory potřebují `node` na PATH (nebo zužte PATH na Python).")
    payload = json.dumps({"root": str(root), "files": files})
    proc = subprocess.run(
        [node, str(HELPER)], input=payload.encode(), capture_output=True, check=False
    )
    if proc.returncode != 0:
        raise CodemapError("codemap-ts.mjs selhal: " + proc.stderr.decode(errors="replace").strip())
    raw = json.loads(proc.stdout)
    tracked_set = set(tracked)
    packages = workspace_packages(root, tracked)
    out: dict[str, FileMap] = {}
    for path in files:
        item = raw[path]
        deps = {
            r
            for spec in item["imports"]
            if (r := resolve_ts_import(path, spec, tracked_set, packages)) and r != path
        }
        out[path] = FileMap(
            path, item["doc"], [_symbol_from_json(s) for s in item["symbols"]], sorted(deps)
        )
    return out


def build_map(root: Path, files: list[str], tracked: list[str]) -> list[FileMap]:
    """Outline every file in ``files`` (sorted by path)."""
    tracked_set = set(tracked)
    maps: dict[str, FileMap] = {}
    ts_files = []
    for path in files:
        if path.endswith(PY_EXT):
            maps[path] = outline_python(root, path, tracked_set)
        else:
            ts_files.append(path)
    maps.update(outline_ts(root, ts_files, tracked))
    return [maps[p] for p in sorted(maps)]


# --- views ----------------------------------------------------------------------------------


def _doc_suffix(doc: str) -> str:
    return f" — {doc}" if doc else " —"


def render_file(fm: FileMap, deps_only: bool) -> str:
    """Text block for one file (see docs/codemap.md for the format)."""
    lines = [fm.path if deps_only else fm.path + _doc_suffix(fm.doc)]
    if fm.deps:
        lines.append("  deps: " + ", ".join(fm.deps))
    if not deps_only:
        for s in fm.symbols:
            lines.append("  " + s.sig + ("" if s.kind == "export" else _doc_suffix(s.doc)))
            lines.extend("    " + m.sig + _doc_suffix(m.doc) for m in s.members)
    return "\n".join(lines) + "\n"


def file_json(fm: FileMap, deps_only: bool) -> dict:
    """JSON object for one file (same content as the text block)."""
    if deps_only:
        return {"path": fm.path, "deps": fm.deps}

    def sym(s: Symbol) -> dict:
        d = {"kind": s.kind, "name": s.name, "sig": s.sig, "doc": s.doc}
        if s.members:
            d["members"] = [sym(m) for m in s.members]
        return d

    return {
        "path": fm.path,
        "doc": fm.doc,
        "deps": fm.deps,
        "symbols": [sym(s) for s in fm.symbols],
    }


def module_key(path: str) -> str:
    """Grouping key for summaries: ``modules/wine``, ``custom_components/homebrain/energy``, …"""
    parts = path.split("/")
    if parts[0] == "custom_components" and len(parts) > 3:
        return "/".join(parts[:3])
    if parts[0] == "custom_components":
        return "/".join(parts[:2])
    return "/".join(parts[:2]) if len(parts) > 2 else parts[0]


def missing_docs(maps: list[FileMap]) -> tuple[list[dict], dict[str, list[int]]]:
    """Per file: undocumented module/public symbols; per module: [missing, total]."""
    files = []
    summary: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for fm in maps:
        missing, total = [], 1
        if not fm.doc or fm.doc.startswith("(syntax error"):
            missing.append("(modul)")
        for s in fm.symbols:
            if s.kind in ("export", "default"):
                continue
            total += 1
            if not s.doc:
                missing.append(s.name)
            for m in s.members:
                total += 1
                if not m.doc:
                    missing.append(f"{s.name}.{m.name}")
        key = module_key(fm.path)
        summary[key][0] += len(missing)
        summary[key][1] += total
        if missing:
            files.append({"path": fm.path, "missing": missing})
    return files, dict(sorted(summary.items()))


def rdeps(maps: list[FileMap], packages: dict[str, str], target: str, depth: int) -> list[dict]:
    """Files importing ``target`` (file or directory), transitively up to ``depth`` levels.

    Importing a workspace package (``@homebrain/ui``) counts as importing its entry
    (``src/index.ts[x]``) and the package directory, not every file inside it.
    """
    target = target.rstrip("/")
    entries = {}
    for pkg_dir in packages.values():
        for e in (f"{pkg_dir}/src/index.ts", f"{pkg_dir}/src/index.tsx", f"{pkg_dir}/index.ts"):
            entries.setdefault(e, pkg_dir)

    def hits(dep: str, goal: str) -> bool:
        return dep == goal or dep.startswith(goal + "/") or entries.get(goal) == dep

    found: dict[str, tuple[int, str]] = {}
    frontier = {target}
    for level in range(1, depth + 1):
        nxt = set()
        for fm in maps:
            if fm.path in found or fm.path == target or fm.path.startswith(target + "/"):
                continue
            via = sorted(g for g in frontier for d in fm.deps if hits(d, g))
            if via:
                found[fm.path] = (level, via[0])
                nxt.add(fm.path)
        if not nxt:
            break
        frontier = nxt
    return [
        {"path": p, "depth": lvl, "via": via}
        for p, (lvl, via) in sorted(found.items(), key=lambda kv: (kv[1][0], kv[0]))
    ]


def truncate(blocks: list[str], max_chars: int | None, reserve: int = 0) -> str:
    """Join whole file blocks up to ``max_chars``; say clearly how much was left out."""
    text = "".join(blocks)
    if max_chars is None or len(text) + reserve <= max_chars:
        return text
    kept, size = [], 0
    room = max_chars - NOTE_RESERVE - reserve  # the note (+ header/summary) fits in too
    for b in blocks:
        if size + len(b) > room:
            break
        kept.append(b)
        size += len(b)
    left = blocks[len(kept) :]
    note = (
        f"… zkráceno (--max-chars {max_chars}): vynecháno {len(left)} z {len(blocks)} bloků, "
        f"{sum(map(len, left))} znaků. Zužte PATH nebo použijte --deps-only.\n"
    )
    return "".join(kept) + note


# --- CLI ------------------------------------------------------------------------------------


def _repo_root(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit).resolve()
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"], capture_output=True, check=True, text=True
        )
    except (OSError, subprocess.CalledProcessError) as err:
        raise CodemapError("codemap běží jen uvnitř git repozitáře (nebo zadejte --root).") from err
    return Path(out.stdout.strip())


def _repo_rel(root: Path, raw: str) -> str:
    p = Path(raw)
    p = (Path.cwd() / p) if not p.is_absolute() else p
    try:
        rel = os.path.relpath(p.resolve(), root)
    except ValueError as err:
        raise CodemapError(f"cesta mimo repozitář: {raw}") from err
    if rel.startswith(".."):
        raise CodemapError(f"cesta mimo repozitář: {raw}")
    return "" if rel == "." else Path(rel).as_posix()


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    """CLI definition (documented in docs/codemap.md)."""
    ap = argparse.ArgumentParser(
        prog="codemap",
        description="Deterministická mapa kódu: soubory, docstringy/JSDoc, signatury, importy.",
    )
    ap.add_argument("paths", nargs="*", metavar="PATH", help="soubory/adresáře (výchozí: celý kód)")
    ap.add_argument("--format", choices=("text", "json"), default="text")
    ap.add_argument("--deps-only", action="store_true", help="jen soubory a jejich závislosti")
    ap.add_argument("--rdeps", metavar="FILE", help="kdo importuje FILE (soubor nebo adresář)")
    ap.add_argument("--depth", type=int, default=1, help="hloubka pro --rdeps (výchozí 1)")
    ap.add_argument("--missing-docs", action="store_true", help="symboly bez docstringu/JSDoc")
    ap.add_argument("--include-tests", action="store_true", help="zahrnout testy")
    ap.add_argument("--max-chars", type=int, metavar="N", help="oříznout výstup na N znaků")
    ap.add_argument("--root", help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if args.depth < 1:
        ap.error("--depth musí být ≥ 1")
    if args.max_chars is not None and args.max_chars < 1:
        ap.error("--max-chars musí být ≥ 1")
    return args


def _json(data: object) -> str:
    return json.dumps(data, ensure_ascii=False) + "\n"


def run(args: argparse.Namespace) -> str:
    """Compute the requested view and return it as text."""
    root = _repo_root(args.root)
    tracked = tracked_files(root)
    paths = [p for p in (_repo_rel(root, raw) for raw in args.paths)]
    if "" in paths:
        paths = []

    if args.rdeps:
        target = _repo_rel(root, args.rdeps)
        universe = build_map(root, select_files(root, tracked, None, args.include_tests), tracked)
        rows = rdeps(universe, workspace_packages(root, tracked), target, args.depth)
        if paths:
            rows = [
                r
                for r in rows
                if any(r["path"] == p or r["path"].startswith(p.rstrip("/") + "/") for p in paths)
            ]
        if args.format == "json":
            return _json({"target": target, "depth": args.depth, "rdeps": rows})
        head = f"rdeps {target} (hloubka {args.depth}): {len(rows)} souborů\n"
        blocks = [
            f"  [{r['depth']}] {r['path']}"
            + (f"  (přes {r['via']})" if r["depth"] > 1 else "")
            + "\n"
            for r in rows
        ]
        return head + truncate(blocks, args.max_chars, len(head))

    files = select_files(root, tracked, paths or None, args.include_tests)
    if paths and not files:
        raise CodemapError("v zadaných cestách nejsou zdrojové soubory (testy: --include-tests)")
    maps = build_map(root, files, tracked)

    if args.missing_docs:
        rows, summary = missing_docs(maps)
        if args.format == "json":
            return _json({"files": rows, "summary": summary})
        blocks = [f"{r['path']}: {', '.join(r['missing'])}\n" for r in rows]
        miss = sum(v[0] for v in summary.values())
        total = sum(v[1] for v in summary.values())
        tail = (
            "souhrn (bez docs / celkem modulů+symbolů):\n"
            + "".join(f"  {k}  {v[0]}/{v[1]}\n" for k, v in summary.items())
            + f"  celkem  {miss}/{total}\n"
        )
        return truncate(blocks, args.max_chars, len(tail)) + tail

    if args.format == "json":
        items = [file_json(fm, args.deps_only) for fm in maps]
        if args.max_chars is not None:
            sizes = [len(_json(i)) for i in items]
            n, size = 0, 0
            while n < len(items) and size + sizes[n] <= args.max_chars - NOTE_RESERVE:
                size += sizes[n]
                n += 1
            if n < len(items):
                left = {"files_left": len(items) - n, "chars_left": sum(sizes[n:])}
                return _json({"files": items[:n], "truncated": left})
        return _json({"files": items})
    return truncate([render_file(fm, args.deps_only) for fm in maps], args.max_chars)


def main(argv: list[str] | None = None) -> int:
    """Entry point; returns the process exit code."""
    args = parse_args(argv)
    try:
        out = run(args)
    except CodemapError as err:
        print(f"codemap: {err}", file=sys.stderr)
        return 2
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
