#!/usr/bin/env node
// Generates packages/ha-client/src/panels.generated.ts from custom_components/homebrain/panels.json,
// the single source of HA panel url paths (const.py reads the JSON directly).
// `node scripts/gen-panels.mjs` writes the file, `--check` fails when it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'custom_components/homebrain/panels.json');
const target = join(root, 'packages/ha-client/src/panels.generated.ts');
const panels = JSON.parse(readFileSync(source, 'utf8'));
const q = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const output = [
  '// Generated by scripts/gen-panels.mjs from custom_components/homebrain/panels.json. Do not edit.',
  '',
  '/** Module id → HA panel url path, exactly as the integration registers it. */',
  'export const PANEL_PATHS_BY_MODULE: Readonly<Record<string, string>> = {',
  ...panels.modules.map((panel) => `  ${panel.module}: ${q(panel.url_path)},`),
  '};',
  `export const SETTINGS_PANEL_PATH = ${q(panels.settings.url_path)};`,
  `export const KIOSK_PANEL_PATH = ${q(panels.kiosk.url_path)};`,
  `export const LEGACY_PANEL_PATH = ${q(panels.legacy.url_path)};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== output) {
    console.error(`${target} is stale; run: node scripts/gen-panels.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
